// Mock 训练指标（生成 67 轮的模拟数据）
const generateMockMetrics = (): RoundMetrics[] => {
  const metrics: RoundMetrics[] = [];
  let loss = 2.5;
  let accuracy = 0.45;

  for (let i = 1; i <= 67; i++) {
    // 模拟 loss 逐渐下降，accuracy 逐渐上升
    loss = Math.max(0.15, loss * 0.96 + (Math.random() - 0.5) * 0.1);
    accuracy = Math.min(0.98, accuracy + 0.007 + (Math.random() - 0.5) * 0.02);

    metrics.push({
      round: i,
      timestamp: new Date(Date.now() - (67 - i) * 10 * 60 * 1000).toISOString(),
      globalLoss: Number(loss.toFixed(4)),
      globalAccuracy: Number(accuracy.toFixed(4)),
      validationLoss: Number((loss * 1.05).toFixed(4)),
      validationAccuracy: Number((accuracy * 0.98).toFixed(4)),
      participatingNodes: i > 65 ? 4 : 5,
      aggregationTime: 2000 + Math.floor(Math.random() * 1000),
    });
  }

  return metrics;
};

